function blitProp(ctx, sprite, tx, ty, ox = 0, oy = 0) {
  if (!sprite) return;
  const px = tx * 16 + ox + Math.floor((16 - sprite.width) / 2);
  const py = ty * 16 + oy + (16 - sprite.height);
  ctx.drawImage(sprite, px, py);
}

function composePatch(rows, propList, tiles, sprites, props, makeCanvas) {
  const h = rows.length;
  const w = rows[0].length;
  const [c, ctx] = makeCanvas(w * 16, h * 16);
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const ch = rows[y][x];
      const tex = TILE_MAP[ch] || 'grass';
      if (tiles[tex]) ctx.drawImage(tiles[tex], x * 16, y * 16);
    }
  }
  const all = { ...sprites, ...props };
  for (const p of propList) {
    const spr = all[p.type];
    if (spr) blitProp(ctx, spr, p.x, p.y, p.ox || 0, p.oy || -8);
  }
  return c;
}

