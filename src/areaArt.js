/**
 * Register sprinkle props, patch previews, area icons, and biome tiles on Art.
 * @param {import('./art.js').Art} Art
 */
export function buildAreaArt(Art, { asciiCanvas, makeCanvas, PAL, mulberry32 }) {
  Art.sprinkles = {};
  Art.sprinkleMeta = {};
  for (const [name, rows] of Object.entries(S)) {
    const w = rows[0].length;
    Art.sprinkles[name] = asciiCanvas(rows, w, rows.length);
    Art.sprinkleMeta[name] = { tags: SPRINKLE_TAGS[name] || [], w, h: rows.length };
  }

  Art.areas = {};
  Art.areaMeta = {
    hamlet: { name: 'Hamlet', tags: ['settlement'] },
    market_town: { name: 'Market town', tags: ['settlement'] },
    walled_city: { name: 'Walled city', tags: ['settlement'] },
    forest_route: { name: 'Forest route', tags: ['route'] },
    limestone_cave: { name: 'Limestone cave', tags: ['underground'] },
    boss_vault: { name: 'Boss vault', tags: ['underground'] },
    river_crossing: { name: 'River crossing', tags: ['route'] },
    badlands_route: { name: 'Badlands route', tags: ['route', 'biome'] },
    inn: { name: 'Inn interior', tags: ['interior'] },
    arena: { name: 'Arena', tags: ['interior'] },
    mushroom_grove: { name: 'Mushroom grove', tags: ['biome'] },
    bell_ruins: { name: 'Bell ruins', tags: ['biome', 'lore'] },
    eldermoor: { name: 'Eldermoor (demo)', tags: ['demo', 'settlement'] },
    hollow_road: { name: 'Hollow Road (demo)', tags: ['demo', 'route'] },
    hollow_cave: { name: 'Hollow Cave (demo)', tags: ['demo', 'underground'] },
    wardens_vault: { name: "Warden's Vault (demo)", tags: ['demo', 'underground'] },
    ashfall: { name: 'Ashfall (demo)', tags: ['demo', 'settlement'] },
  };
  for (const [name, rows] of Object.entries(AREA_ICONS)) {
    Art.areas[name] = asciiCanvas(rows);
  }

  const biomes = buildBiomeTiles(makeCanvas, mulberry32, PAL);
  Art.biomes = biomes;
  Art.biomeMeta = {
    marsh: { name: 'Bone marsh', tags: ['biome', 'water'] },
    reeds: { name: 'Reed bed', tags: ['biome', 'water'] },
    ashground: { name: 'Ash scrub ground', tags: ['biome'] },
    saltcrack: { name: 'Salt flats', tags: ['biome'] },
    mossfloor: { name: 'Ruin moss', tags: ['biome', 'lore'] },
    bellstone: { name: 'Bell stone', tags: ['biome', 'lore'] },
    mushroom_floor: { name: 'Mushroom floor', tags: ['biome', 'cozy'] },
    tideline: { name: 'Tide line', tags: ['biome', 'water'] },
  };
  for (const [k, canvas] of Object.entries(biomes)) {
    Art.tiles[k] = canvas;
  }

  Art.patches = {};
  Art.patchMeta = {};
  Art.patchGroups = PATCH_GROUPS;
  for (const def of PATCH_DEFS) {
    Art.patches[def.id] = composePatch(def.rows, def.props, Art.tiles, Art.sprinkles, Art.props, makeCanvas);
    Art.patchMeta[def.id] = {
      name: def.name,
      group: def.group,
      tags: def.tags,
      w: def.rows[0].length,
      h: def.rows.length,
    };
  }
}

