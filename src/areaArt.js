function makeTileCanvas(makeCanvas, mulberry32, PAL, painter, seed = 1) {
  const [c, ctx] = makeCanvas(16, 16);
  painter(ctx, mulberry32(seed), PAL);
  return c;
}
function fill(ctx, PAL, shade) { ctx.fillStyle = PAL[shade]; ctx.fillRect(0, 0, 16, 16); }
function speck(ctx, PAL, rnd, shade, n) {
  ctx.fillStyle = PAL[shade];
  for (let i = 0; i < n; i++) ctx.fillRect((rnd() * 16) | 0, (rnd() * 16) | 0, 1, 1);
}

