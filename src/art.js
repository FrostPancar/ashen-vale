// deterministic rng for tile noise
export function mulberry32(a) {
  return function() {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function makeCanvas(w, h) {
  const c = document.createElement('canvas');
  c.width = w; c.height = h;
  const ctx = c.getContext('2d');
  ctx.imageSmoothingEnabled = false;
  return [c, ctx];
}

// Draw ascii sprite onto ctx at (ox,oy). chars: '.'=transparent, '0'-'3'=palette
export function drawAscii(ctx, rows, ox = 0, oy = 0) {
  for (let y = 0; y < rows.length; y++) {
    const row = rows[y];
    for (let x = 0; x < row.length; x++) {
      const ch = row[x];
      if (ch === '.' || ch === ' ') continue;
      ctx.fillStyle = PAL[+ch];
      ctx.fillRect(ox + x, oy + y, 1, 1);
    }
  }
}

export function asciiCanvas(rows, w, h) {
  const W = w || Math.max(...rows.map(r => r.length));
  const H = h || rows.length;
  const [c, ctx] = makeCanvas(W, H);
  drawAscii(ctx, rows);
  return c;
}

function mirrored(rows) {
  return rows.map(r => r.split('').reverse().join(''));
}

export function canvasTexture(canvas) {
  const t = new THREE.CanvasTexture(canvas);
  t.magFilter = THREE.NearestFilter;
  t.minFilter = THREE.NearestFilter;
  t.colorSpace = THREE.SRGBColorSpace;
  return t;
}

