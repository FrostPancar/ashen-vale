function buildCharFrames(klass) {
  // returns { down:[c0,c1], up:[c0,c1], left:[..], right:[..] }
  const out = {};
  const mk = (bodyRows, dir) => {
    const [c, ctx] = makeCanvas(16, 16);
    drawAscii(ctx, bodyRows);
    const ov = OVERLAYS[klass];
    if (ov) drawAscii(ctx, ov[dir] || ov.down, 0, 0);
    if (klass === 'elder') drawAscii(ctx, ELDER_BEARD, 0, 0);
    return c;
  };
  out.down = [mk(BODY.down0, 'down'), mk(BODY.down1, 'down')];
  out.up = [mk(BODY.up0, 'up'), mk(BODY.up1, 'up')];
  out.right = [mk(BODY.side0, 'side'), mk(BODY.side1, 'side')];
  out.left = [mk(mirrored(BODY.side0), 'side'), mk(mirrored(BODY.side1), 'side')];
  // mirror overlays for left got re-applied unmirrored; redo left properly:
  out.left = [0, 1].map(i => {
    const [c, ctx] = makeCanvas(16, 16);
    const body = mirrored(i === 0 ? BODY.side0 : BODY.side1);
    drawAscii(ctx, body);
    const ov = OVERLAYS[klass];
    if (ov) drawAscii(ctx, mirrored((ov.side || ov.down).map(r => r.padEnd(16, '.'))), 0, 0);
    if (klass === 'elder') drawAscii(ctx, ELDER_BEARD, 0, 0);
    return c;
  });
  return out;
}

/* ================= NPC variants ================= */
function buildNpc(hatShade, robeShade) {
  // simple recolor: draw body then tint shirt rows
  const frames = buildCharFrames(null);
  for (const dir of ['down', 'up', 'left', 'right']) {
    for (const c of frames[dir]) {
      const ctx = c.getContext('2d');
      // hat band
      ctx.fillStyle = PAL[hatShade];
      ctx.fillRect(5, 1, 6, 1);
      if (robeShade != null) {
        ctx.fillStyle = PAL[robeShade];
        ctx.fillRect(5, 10, 6, 2);
      }
    }
  }
  return frames;
}

