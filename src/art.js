export function paintOrb(big) {
  const n = big ? 12 : 10;
  const [c, ctx] = makeCanvas(n, n);
  const cx = n / 2, cy = n / 2;
  const ring = (r, shade, a = 1) => {
    ctx.fillStyle = PAL[shade];
    ctx.globalAlpha = a;
    for (let y = 0; y < n; y++) for (let x = 0; x < n; x++) {
      const d = Math.hypot(x + 0.5 - cx, y + 0.5 - cy);
      if (d <= r && d > r - 1.4) ctx.fillRect(x, y, 1, 1);
    }
    ctx.globalAlpha = 1;
  };
  ring(cx, 1, 0.7);          // soft dark rim
  ring(cx - 0.8, 2);         // mid shell
  ctx.fillStyle = PAL[3];    // bright cross-shaped core
  ctx.fillRect(cx - 2, cy - 1, 4, 2); ctx.fillRect(cx - 1, cy - 2, 2, 4);
  ctx.fillStyle = PAL[2];    // off-centre spark for life
  ctx.fillRect((cx + 1) | 0, (cy - 2) | 0, 1, 1);
  return c;
}

// Glowing thorn-seal target — concentric rune rings with a bright core, so the
// player can read at a glance where the wakestone is meant to come to rest.
export function paintSealMarker() {
  const n = 32;
  const [c, ctx] = makeCanvas(n, n);
  const cx = n / 2, cy = n / 2;
  const band = (r, wdt, shade, a = 1) => {
    ctx.fillStyle = PAL[shade]; ctx.globalAlpha = a;
    for (let y = 0; y < n; y++) for (let x = 0; x < n; x++) {
      const d = Math.hypot(x + 0.5 - cx, y + 0.5 - cy);
      if (d <= r && d > r - wdt) ctx.fillRect(x, y, 1, 1);
    }
    ctx.globalAlpha = 1;
  };
  band(15, 2.6, 0, 0.9);     // outer thorn ring (dark)
  band(11, 2.0, 3, 0.95);    // glowing rune ring (bright)
  band(7.5, 1.8, 1, 0.8);    // inner shadow groove
  // bright center diamond (the socket the wakestone wants)
  ctx.fillStyle = PAL[3];
  for (let y = 0; y < n; y++) for (let x = 0; x < n; x++) {
    if (Math.abs(x + 0.5 - cx) + Math.abs(y + 0.5 - cy) < 4.5) ctx.fillRect(x, y, 1, 1);
  }
  // cardinal thorn ticks notching the outer ring
  ctx.fillStyle = PAL[0];
  ctx.fillRect(cx - 1, 0, 2, 4); ctx.fillRect(cx - 1, n - 4, 2, 4);
  ctx.fillRect(0, cy - 1, 4, 2); ctx.fillRect(n - 4, cy - 1, 4, 2);
  return c;
}

/* ================= TILE TEXTURES (16x16 patterns) ================= */
function tileCanvas(painter, seed = 1) {
  const [c, ctx] = makeCanvas(16, 16);
  painter(ctx, mulberry32(seed));
  return c;
}
function fill(ctx, shade) { ctx.fillStyle = PAL[shade]; ctx.fillRect(0, 0, 16, 16); }
function speck(ctx, rnd, shade, n) {
  ctx.fillStyle = PAL[shade];
  for (let i = 0; i < n; i++) ctx.fillRect((rnd() * 16) | 0, (rnd() * 16) | 0, 1, 1);
}
function px(ctx, shade, x, y) {
  if (x < 0 || y < 0 || x > 15 || y > 15) return;
  ctx.fillStyle = PAL[shade];
  ctx.fillRect(x, y, 1, 1);
}
// short grass blade (1–2 px) for ground tiles
function grassBlade(ctx, x, y, h, lean = 0) {
  px(ctx, 1, x, y + h - 1);
  if (h > 1) px(ctx, 1, x, y + h - 2);
  if (lean < 0 && h > 1) px(ctx, 2, x - 1, y + h - 2);
  if (lean > 0 && h > 1) px(ctx, 2, x + 1, y + h - 2);
  px(ctx, 3, x + (lean < 0 ? -1 : lean > 0 ? 1 : 0), y);
}
// tall grass tuft — Gen-1 route grass silhouette
function grassTuft(ctx, x, y, h) {
  px(ctx, 0, x + 1, y + 2);
  px(ctx, 0, x + 1, y + 3);
  for (let i = 0; i < h; i++) {
    px(ctx, 1, x, y + i);
    if (i > 0) px(ctx, 1, x - 1, y + i);
    if (i > 1) px(ctx, 1, x + 1, y + i - 1);
  }
  px(ctx, 2, x - 1, y);
  px(ctx, 2, x, y);
  px(ctx, 3, x - 1, y - 1);
}
function grassPatch(ctx, coords) {
  ctx.fillStyle = PAL[1];
  for (const [x, y, w, h] of coords) ctx.fillRect(x, y, w, h);
}
function drawFlower(ctx, cx, cy) {
  px(ctx, 1, cx, cy + 2);
  px(ctx, 2, cx, cy + 1);
  px(ctx, 3, cx - 1, cy); px(ctx, 3, cx + 1, cy);
  px(ctx, 3, cx, cy - 1); px(ctx, 3, cx, cy + 1);
  px(ctx, 0, cx, cy);
}

